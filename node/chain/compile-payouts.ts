// Compile contracts/TesseraPayouts.sol (AUSD settlement on Base Sepolia) and write its ABI + bytecode.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = fileURLToPath(new URL("../..", import.meta.url));
const source = readFileSync(path.join(root, "contracts/TesseraPayouts.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "TesseraPayouts.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const findImports = (p: string) => {
  try {
    return { contents: readFileSync(path.join(root, "node_modules", p), "utf8") };
  } catch {
    return { error: `not found: ${p}` };
  }
};
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
const c = out.contracts["TesseraPayouts.sol"].TesseraPayouts;
writeFileSync(
  path.join(root, "src/chain/payoutsAbi.ts"),
  `// Generated by node/chain/compile-payouts.ts. Do not edit.\n` +
    `export const payoutsAbi = ${JSON.stringify(c.abi)} as const;\n` +
    `export const payoutsBytecode = "0x${c.evm.bytecode.object}" as const;\n`,
);
console.log("compiled; payouts bytecode", c.evm.bytecode.object.length / 2, "bytes");
