// Compile contracts/TesseraLedger.sol with solc-js and write ABI + bytecode for the app and scripts.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = fileURLToPath(new URL("../..", import.meta.url));
const source = readFileSync(path.join(root, "contracts/TesseraLedger.sol"), "utf8");

const input = {
  language: "Solidity",
  sources: { "TesseraLedger.sol": { content: source } },
  settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
};
const findImports = (p: string) => {
  try {
    return { contents: readFileSync(path.join(root, "node_modules", p), "utf8") };
  } catch {
    return { error: `not found: ${p}` };
  }
};
const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
const c = out.contracts["TesseraLedger.sol"];
mkdirSync(path.join(root, "src/chain"), { recursive: true });
writeFileSync(
  path.join(root, "src/chain/abi.ts"),
  `// Generated by node/chain/compile.ts. Do not edit.\n` +
    `export const ledgerAbi = ${JSON.stringify(c.TesseraLedger.abi)} as const;\n` +
    `export const cusdAbi = ${JSON.stringify(c.ConsortiumUSD.abi)} as const;\n` +
    `export const ledgerBytecode = "0x${c.TesseraLedger.evm.bytecode.object}" as const;\n`,
);
console.log("compiled; ledger bytecode", c.TesseraLedger.evm.bytecode.object.length / 2, "bytes");
