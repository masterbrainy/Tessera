// Compile and deploy TesseraPayoutRouter to Ethereum Sepolia (AUSD lives there), writing
// src/chain/routerAbi.ts and src/chain/router.json. Uses PAYOUT_KEY from .env for gas.
// Usage: npx tsx node/chain/deploy-router.ts [--compile-only]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createPublicClient, createWalletClient, formatEther, http, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { sepolia } from "viem/chains";

const require = createRequire(import.meta.url);
const solc = require("solc");
const root = fileURLToPath(new URL("../..", import.meta.url));
const RPC = "https://ethereum-sepolia-rpc.publicnode.com";

function compile() {
  const input = {
    language: "Solidity",
    sources: { "TesseraPayoutRouter.sol": { content: readFileSync(path.join(root, "contracts/TesseraPayoutRouter.sol"), "utf8") } },
    settings: { optimizer: { enabled: true, runs: 200 }, viaIR: true, evmVersion: "paris", outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } } },
  };
  const findImports = (p: string) => {
    try {
      return { contents: readFileSync(path.join(root, "node_modules", p), "utf8") };
    } catch {
      return { error: `not found: ${p}` };
    }
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
  const errors = (out.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
  if (errors.length) throw new Error(errors.map((e: { formattedMessage: string }) => e.formattedMessage).join("\n"));
  const c = out.contracts["TesseraPayoutRouter.sol"].TesseraPayoutRouter;
  writeFileSync(
    path.join(root, "src/chain/routerAbi.ts"),
    `// Generated by node/chain/deploy-router.ts. Do not edit.\nexport const routerAbi = ${JSON.stringify(c.abi)} as const;\n`,
  );
  return { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` as Hex };
}

function payoutKey(): Hex {
  const env = path.join(root, ".env");
  const key = process.env.PAYOUT_KEY ?? (existsSync(env) ? readFileSync(env, "utf8").match(/^PAYOUT_KEY=(0x[0-9a-fA-F]{64})$/m)?.[1] : undefined);
  if (!key) throw new Error("PAYOUT_KEY missing from .env");
  return key as Hex;
}

const { abi, bytecode } = compile();
console.log("compiled; bytecode", (bytecode.length - 2) / 2, "bytes");
if (!process.argv.includes("--compile-only")) {
  const account = privateKeyToAccount(payoutKey());
  const pub = createPublicClient({ chain: sepolia, transport: http(RPC) });
  const wallet = createWalletClient({ account, chain: sepolia, transport: http(RPC) });
  console.log("deployer", account.address, "balance", formatEther(await pub.getBalance({ address: account.address })), "ETH");
  const hash = await wallet.deployContract({ abi, bytecode });
  const receipt = await pub.waitForTransactionReceipt({ hash });
  if (!receipt.contractAddress) throw new Error("deploy failed");
  const out = { chainId: sepolia.id, router: receipt.contractAddress, deployTx: hash, explorer: "https://sepolia.etherscan.io" };
  writeFileSync(path.join(root, "src/chain/router.json"), JSON.stringify(out, null, 2) + "\n");
  console.log("router", receipt.contractAddress, "tx", hash);
}
